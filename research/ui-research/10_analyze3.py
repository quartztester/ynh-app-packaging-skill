#!/usr/bin/env python3
"""Round-3 aggregate over 30 apps + scale probes (is_public legacy, bilingual, defaults)."""
import os, tomllib, statistics, json, re

BASE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data3")
sel = json.load(open("round3_selection.json"))
APPS = [a for a, _, _ in sel]

STANDARD = {"domain", "path", "user", "group", "admin", "admin_pass", "password",
            "init_main_permission", "init_admin_permission", "is_public", "language"}

qc, ids, types_seen = [], {}, set()
std_ask_nonempty, custom_total, custom_no_default, custom_no_fr, optional_any = 0, 0, 0, 0, 0
path_omitted, is_public_legacy = 0, []
for app in APPS:
    try:
        m = tomllib.load(open(os.path.join(BASE, app, "manifest.toml"), "rb"))
    except Exception as e:
        print(f"!! {app} manifest parse fail: {e}"); continue
    args = m.get("install", {})
    qc.append(len(args))
    if "path" not in args: path_omitted += 1
    for k, v in args.items():
        ids[k] = ids.get(k, 0) + 1
        t = v.get("type", "string" if k not in ("domain",) else "domain")
        types_seen.add(t)
        ask = v.get("ask", {})
        en = ask.get("en", "") if isinstance(ask, dict) else ""
        if k in {"domain", "path", "init_main_permission", "init_admin_permission", "admin", "is_public"} and en:
            std_ask_nonempty += 1
        if k not in STANDARD:
            custom_total += 1
            if "default" not in v and not v.get("optional"): custom_no_default += 1
            if isinstance(ask, dict) and "en" in ask and "fr" not in ask: custom_no_fr += 1
        if v.get("optional"): optional_any += 1
        if k == "is_public": is_public_legacy.append(app)

print(f"apps={len(qc)} questions: median={statistics.median(qc)} mean={statistics.mean(qc):.1f} range={min(qc)}-{max(qc)}")
big = sorted(zip(qc, APPS), reverse=True)[:5]
print("most questions:", big)
print(f"path omitted: {path_omitted}/30 | is_public legacy: {is_public_legacy or 'NONE'}")
print(f"std-type questions with NON-empty ask.en: {std_ask_nonempty}")
print(f"custom questions: {custom_total} | no-default: {custom_no_default} | en-but-no-fr ask: {custom_no_fr} | optional anywhere: {optional_any}")
print("ids by freq:", sorted(ids.items(), key=lambda x: -x[1]))
print("types:", sorted(types_seen))
print()
print("== panels:")
for app in [a for a in APPS if os.path.exists(os.path.join(BASE, a, "config_panel.toml"))]:
    t = tomllib.load(open(os.path.join(BASE, app, "config_panel.toml"), "rb"))
    nopts = nbind = nbtn = nvis = 0
    secs = []
    for sec_name, sec in t.items():
        if not isinstance(sec, dict): continue
        for sub_name, sub in sec.items():
            if not isinstance(sub, dict): continue
            opts = {k: v for k, v in sub.items() if isinstance(v, dict) and "type" in v}
            if not opts: continue
            secs.append(sub_name); nopts += len(opts)
            nbind += sum(1 for v in opts.values() if "bind" in v)
            nbtn += sum(1 for v in opts.values() if v["type"] == "button")
            nvis += sum(1 for v in opts.values() if "visible" in v)
    print(f"  {app:14s} sections={secs} opts={nopts} bind={nbind} btn={nbtn} visible={nvis}")
print()
print("== ADMIN.md lines:")
for app in APPS:
    p = os.path.join(BASE, app, "doc_ADMIN.md")
    if os.path.exists(p):
        print(f"  {app:16s} {sum(1 for _ in open(p)):4d}")
print()
print("== README bot-marker + description source probe:")
for app in ["gitea", "adguardhome", "anarchism", "bookwyrm"]:
    txt = open(os.path.join(BASE, app, "README.md")).read()
    marker = "auto-generated" in txt.lower() or "readme_generator" in txt.lower() or "generated by" in txt.lower()
    m = tomllib.load(open(os.path.join(BASE, app, "manifest.toml"), "rb"))
    desc = m.get("description", {})
    print(f"  {app:14s} bot_marker={marker} manifest_desc_en={'en' in desc} desc_len={len(desc.get('en',''))}")
